/* ==========================================================================
   照片清单 —— 以后加照片，只改这一个文件，不用碰任何 HTML
   --------------------------------------------------------------------------
   一张照片 = 一条 {}，只有四个字段必须记：

     slug   图片文件名（不带 -800 / -1600，也不带 .jpg）
            文件要放在同目录的 photos/ 里，两张尺寸：
              photos/<slug>-800.jpg    宽 800px
              photos/<slug>-1600.jpg   宽 1600px（暂时只有 800 那张也能显示）
            slug 建议用英文小写 + 连字符，例如 hai-bian、jia-li-de-mao
            留空字符串 '' = 这一格先放着，页面会显示一块纸色占位 +「待填」

     src    可选。照片存在网上的完整链接（https:// 开头那种）。
            用页面最底下「贴一张新照片」传上去，会自动生成这一行。
            有 src 时优先用它，不必再往 photos/ 里放文件；
            没写 src 才按 slug 去找本地 photos/<slug>-800.jpg。

     time   拍摄时间。想写多随意都行：2026.08 / 2026 夏天 / 某个周日下午
     place  地点。两个字也行：海边 / 家门口 / 学校的操场
     note   一句心情。这一句用手写体显示在照片下面

   size 是可选的：'l' 大 / 'm' 中 / 's' 小。
   不填的话程序会按 l m s m l s 轮流分配，出来的版式错落一点。

   要加一组：复制一整个 { title, desc, photos: [ ... ] } 粘在 groups 里。
   注意最后一组后面不要多写一个逗号（老浏览器会报错）。
   ========================================================================== */

